const engAnchor = "    searchEmptyHint: 'Try Hausa proverb, Yoruba folktale, or Igbo tradition',";
const hausaAnchor = "    searchEmptyHint: 'Gwada tatsuniyar Hausa, karin magana, ko al\\'adar Hausawa',";

function buildKeyBlock(obj) {
  return '\n' + Object.entries(obj).map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`).join('\n');
}

const engBlock = buildKeyBlock(keys.english);
const hausaBlock = buildKeyBlock(keys.hausa);

console.log('eng anchor found:', t.includes(engAnchor));
console.log('hausa anchor found:', t.includes(hausaAnchor));

t = t.replace(engAnchor, engAnchor + engBlock);
t = t.replace(hausaAnchor, hausaAnchor + hausaBlock);

fs.writeFileSync(f, t, 'utf8');
console.log('done, length:', t.length);
