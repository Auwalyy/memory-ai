        {ingestion.detectedLanguage && (
          <Badge variant="secondary" className="text-xs capitalize">Detected: {ingestion.detectedLanguage}</Badge>
        )}
        {ingestion.outputLanguage && ingestion.outputLanguage !== ingestion.detectedLanguage && (
          <Badge variant="default" className="text-xs capitalize">Output: {ingestion.outputLanguage}</Badge>
        )}
