function buildExportText(ingestion, fileName) {
  const lines = [];
  lines.push(`MemoryAI Nigeria — Analysis Report`);
  lines.push(`File: ${fileName || 'Unknown'}`);
  lines.push(`Detected Language: ${ingestion.detectedLanguage || ''}`);
  if (ingestion.outputLanguage && ingestion.outputLanguage !== ingestion.detectedLanguage)
    lines.push(`Output Language: ${ingestion.outputLanguage}`);
  lines.push(`Content Type: ${(ingestion.contentType || '').replace(/_/g, ' ')}`);
  lines.push('');
  if (ingestion.metadata?.title) lines.push(`Title: ${ingestion.metadata.title}`);
  if (ingestion.summaries?.short) { lines.push(''); lines.push('Summary:'); lines.push(ingestion.summaries.short); }
  if (ingestion.summaries?.medium) { lines.push(''); lines.push('Detailed Summary:'); lines.push(ingestion.summaries.medium); }
  if (ingestion.aiUnderstanding?.mainTheme) { lines.push(''); lines.push(`Main Theme: ${ingestion.aiUnderstanding.mainTheme}`); }
  if (ingestion.aiUnderstanding?.moralLessons?.length) {
    lines.push(''); lines.push('Moral Lessons:');
    ingestion.aiUnderstanding.moralLessons.forEach((l) => lines.push(`  • ${l}`));
  }
  if (ingestion.aiUnderstanding?.culturalMeaning) { lines.push(''); lines.push('Cultural Meaning:'); lines.push(ingestion.aiUnderstanding.culturalMeaning); }
  if (ingestion.aiUnderstanding?.historicalContext) { lines.push(''); lines.push('Historical Context:'); lines.push(ingestion.aiUnderstanding.historicalContext); }
  if (ingestion.aiUnderstanding?.educationalValue) { lines.push(''); lines.push('Educational Value:'); lines.push(ingestion.aiUnderstanding.educationalValue); }
  const e = ingestion.entities || {};
  const entityGroups = [
    ['People', e.people], ['Places', e.places], ['Communities', e.communities],
    ['Traditions', e.traditions], ['Festivals', e.festivals], ['Keywords', e.keywords],
  ].filter(([, v]) => v?.length);
  if (entityGroups.length) {
    lines.push(''); lines.push('Extracted Entities:');
    entityGroups.forEach(([label, items]) => lines.push(`  ${label}: ${items.join(', ')}`));
  }
  if (ingestion.metadata?.tags?.length) { lines.push(''); lines.push(`Tags: ${ingestion.metadata.tags.join(', ')}`); }
  lines.push(''); lines.push('— Generated by MemoryAI Nigeria');
  return lines.join('\n');
}

function exportAsTxt(ingestion, fileName) {
  const content = buildExportText(ingestion, fileName);
  const blob = new Blob([content], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = `${(fileName || 'analysis').replace(/\.[^.]+$/, '')}-memoryai.txt`;
  a.click(); URL.revokeObjectURL(url);
}

